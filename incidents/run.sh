#!/usr/bin/env bash
# Harmless local incident reconstruction. No attack traffic, no production changes.
set -euo pipefail
cd "$(dirname "$0")/.."
out=${1:-incident-output}
mkdir -p "$out"; out=$(realpath "$out")
t=$(mktemp -d); trap 'rm -rf "$t"' EXIT
export HK_STATE="$t/state" HK_ALERT_CHANNELS=log HK_CONSECUTIVE=1 NO_COLOR=1
# All tampering is confined to a newly generated fixture root.
tests/make-fixtures.sh "$t/fx" >/dev/null
root=$t/fx/hardened
./hk audit --root "$root" --format json > "$out/before.json"
./hk baseline create --root "$root" > "$out/baseline.txt"
printf 'ssh-ed25519 DEMO-UNAUTHORIZED-KEY\n' >> "$root/home/alice/.ssh/authorized_keys"
printf '#!/bin/sh\necho demo\n' > "$root/tmp/rootshell"; chmod 4755 "$root/tmp/rootshell"
./hk drift --root "$root" > "$out/drift.txt" && exit 1 || test $? -eq 1
./hk audit --root "$root" --only FS-004 --format json > "$out/detected.json"
grep -q '"status":"FAIL"' "$out/detected.json"
./hk fix --root "$root" --apply FS-004 > "$out/containment.txt"
[[ $(stat -c %a "$root/tmp/rootshell") == 755 ]]
tx=$(find "$HK_STATE/tx" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' | head -1)
./hk rollback "$tx" > "$out/rollback.txt"
[[ $(stat -c %a "$root/tmp/rootshell") == 4755 ]]
# Rollback undoes the fix, NOT the attack. Eradicate the injected artifacts explicitly.
rm "$root/tmp/rootshell"
sed -i '/DEMO-UNAUTHORIZED-KEY/d' "$root/home/alice/.ssh/authorized_keys"
./hk drift --root "$root" > "$out/recovered.txt"
export HK_AUTH_LOG="$t/auth.log"
now=$(date -u +%FT%T+00:00)
for _ in $(seq 1 110); do echo "$now host sshd[1]: Failed password for root from 203.0.113.9 port 22 ssh2"; done > "$HK_AUTH_LOG"
./hk monitor once --simulate mem=1 > "$out/monitor.txt" || test $? -le 2
grep -q '203.0.113.9' "$out/monitor.txt"
cp "$HK_STATE/alerts.log" "$out/alerts.log"
cp "$HK_STATE/hk.prom" "$out/metrics.prom"
python3 - "$out" <<'END'
import json,sys,datetime
from pathlib import Path
p=Path(sys.argv[1]);before=json.loads((p/'before.json').read_text());det=json.loads((p/'detected.json').read_text())
(p/'report.md').write_text(f"""# Incident drill report

Generated UTC: {datetime.datetime.now(datetime.timezone.utc).isoformat()}
Scope: disposable filesystem fixture plus synthetic SSH log records, not a real exploit.

## Timeline
1. Baseline recorded. Audit score: {before['score']}.
2. Simulated attacker added a demo key and a harmless SUID shell file.
3. Drift detected file/key changes; FS-004 detected the SUID artifact: {det['results'][0]['status']}.
4. Containment removed the SUID bit, verified mode 755.
5. Transaction rollback restored mode 4755, verified. This intentionally demonstrates why rollback is not incident recovery.
6. Eradication removed the demo key and file; baseline drift returned clean.
7. 110 synthetic SSH failures from documentation-only IP 203.0.113.9 were detected; no network requests were made to that IP.

## Evidence
before.json, detected.json, drift.txt, containment.txt, rollback.txt, recovered.txt, monitor.txt, alerts.log and metrics.prom are machine-generated by run.sh.

## Lessons
Review keys and privilege changes, preserve evidence, contain, then eradicate. Never blindly roll back a security fix on a compromised live host. This lab does not prove exploit resistance, automatic attacker blocking, or full forensic chain of custody.
""")
END
echo "PASS: incident detection, containment, rollback, eradication and brute-force log detection; report=$out/report.md"
